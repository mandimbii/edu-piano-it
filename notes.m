% FERMETURE
% ============================================================

    function fermerFenetre(~,~)

        try

            if ~isempty(parentFigure) && ...
                    ishandle(parentFigure)

                set(parentFigure,'Visible','on');
                figure(parentFigure);

            end

        catch
        end

        delete(f);

    end

