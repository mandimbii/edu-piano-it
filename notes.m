% ============================================================
% COLORER UNE NOTE
% ============================================================

    function colorerChromatique(indice,octave)

        % ----------------------------------------------------
        % BLANCHE
        % ----------------------------------------------------

        if ismember(indice,[1 3 5 6 8 10 12])

            position = ...
                trouverPositionBlanche( ...
                indice,octave);

            if position > 0

                set( ...
                    touchesBlanches{position}, ...
                    'BackgroundColor',bleuCiel, ...
                    'ForegroundColor',blanc);

            end

        % ----------------------------------------------------
        % NOIRE
        % ----------------------------------------------------

        else

            position = ...
                trouverPositionNoire( ...
                indice,octave);

            if position > 0

                set( ...
                    touchesNoires{position}, ...
                    'BackgroundColor',rouge, ...
                    'ForegroundColor',blanc);

            end

        end

    end

% ============================================================
% TROUVER POSITION BLANCHE
% ============================================================

    function position = ...
        trouverPositionBlanche(indice,octave)

        position = 0;

        correspondances = { ...
            [1 5], ...
            [3 5], ...
            [5 5], ...
            [6 5], ...
            [8 5], ...
            [10 5], ...
            [12 5], ...
            [1 6], ...
            [3 6], ...
            [5 6], ...
            [6 6], ...
            [8 6], ...
            [10 6], ...
            [12 6], ...
            [1 7]};

        for i = 1:15

            if correspondances{i}(1) == indice && ...
               correspondances{i}(2) == octave

                position = i;
                return;

            end

        end

    end

