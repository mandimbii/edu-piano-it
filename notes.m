% ============================================================
% AFFICHAGE NOTE
% ============================================================

    function afficherNote()

        % ----------------------------------------------------
        % NOTE BLANCHE
        % ----------------------------------------------------

        if typeNoteSelectionne == 1

            nomFrancais = ...
                nomsBlanchesMenu{noteSelectionnee};

            nomInternational = ...
                nomsInternationauxBlanches{noteSelectionnee};

            frequence = ...
                frequencesBlanchesBase(noteSelectionnee);

            titre = nomFrancais;

            sousTitreTexte = ...
                [nomInternational ' - ' ...
                 num2str(frequence,'%.2f') ' Hz'];

            information = construireInformationsBlanche( ...
                noteSelectionnee,nomFrancais, ...
                nomInternational,frequence);

            explication = ...
                obtenirExplicationBlanche( ...
                noteSelectionnee);

            couleurTitre = bleuCiel;

        % ----------------------------------------------------
        % NOTE NOIRE
        % ----------------------------------------------------

        else

            nomFrancais = ...
                nomsNoiresMenu{noteSelectionnee};

            nomBemol = ...
                nomsBemols{noteSelectionnee};

            nomInternational = ...
                nomsInternationauxNoires{noteSelectionnee};

            frequence = ...
                frequencesNoiresBase(noteSelectionnee);

            titre = nomFrancais;

            sousTitreTexte = ...
                [nomInternational ' / ' ...
                 nomBemol ' - ' ...
                 num2str(frequence,'%.2f') ' Hz'];

            information = construireInformationsNoire( ...
                noteSelectionnee,nomFrancais, ...
                nomBemol,nomInternational,frequence);

            explication = ...
                obtenirExplicationNoire( ...
                noteSelectionnee);

            couleurTitre = rouge;

        end

        % ----------------------------------------------------
        % TITRE
        % ----------------------------------------------------

        set( ...
            titreNote, ...
            'String',titre, ...
            'ForegroundColor',couleurTitre);

        % ----------------------------------------------------
        % SOUS-TITRE
        % ----------------------------------------------------

        set( ...
            sousTitre, ...
            'String',sousTitreTexte);

        % ----------------------------------------------------
        % INFORMATIONS
        % ----------------------------------------------------

        set( ...
            texteInformation, ...
            'String',information, ...
            'Value',1);

        % ----------------------------------------------------
        % EXPLICATION
        % ----------------------------------------------------

        set( ...
            texteExplication, ...
            'String',explication, ...
            'Value',1);

        % ----------------------------------------------------
        % RESET DU CLAVIER
        % ----------------------------------------------------

        for i = 1:15

            set( ...
                touchesBlanches{i}, ...
                'BackgroundColor',blanc, ...
                'ForegroundColor',noir);

        end

        for i = 1:10

            set( ...
                touchesNoires{i}, ...
                'BackgroundColor',noir, ...
                'ForegroundColor',blanc);

        end

        % ----------------------------------------------------
        % INDICE CHROMATIQUE
        % ----------------------------------------------------

        if typeNoteSelectionne == 1

            indiceChromatique = ...
                obtenirIndiceBlanche(noteSelectionnee);

        else

            indiceChromatique = ...
                obtenirIndiceNoire(noteSelectionnee);

        end

        % ----------------------------------------------------
        % HIGHLIGHT OCTAVE 5
        % ----------------------------------------------------

        colorerChromatique( ...
            indiceChromatique,5);

        % ----------------------------------------------------
        % HIGHLIGHT OCTAVE 6
        % ----------------------------------------------------

        colorerChromatique( ...
            indiceChromatique,6);

        % ----------------------------------------------------
        % DO7
        % ----------------------------------------------------

        if indiceChromatique == 1

            set( ...
                touchesBlanches{15}, ...
                'BackgroundColor',bleuCiel, ...
                'ForegroundColor',blanc);

        end

        drawnow;

    end

