% ACTUALISER LE MENU
% ============================================================

    function actualiserMenu()

        for i = 1:7

            set( ...
                boutonsBlanches{i}, ...
                'BackgroundColor',bleuClair, ...
                'ForegroundColor',bleuFonce);

        end

        for i = 1:5

            set( ...
                boutonsNoiresMenu{i}, ...
                'BackgroundColor',noir, ...
                'ForegroundColor',blanc);

        end

        if typeNoteSelectionne == 1

            set( ...
                boutonsBlanches{noteSelectionnee}, ...
                'BackgroundColor',bleuCiel, ...
                'ForegroundColor',blanc);

        else

            set( ...
                boutonsNoiresMenu{noteSelectionnee}, ...
                'BackgroundColor',rouge, ...
                'ForegroundColor',blanc);

        end

    end

% ============================================================
% CLIC TOUCHE BLANCHE DU CLAVIER
% ============================================================

    function clicToucheBlanche(~,~,indice)

        nom = nomsBlanches{indice};

        note = strrep(nom,'5','');
        note = strrep(note,'6','');
        note = strrep(note,'7','');

        tableau = {'C','D','E','F','G','A','B'};

        for i = 1:7

            if strcmp(tableau{i},note)

                noteSelectionnee = i;
                typeNoteSelectionne = 1;

                afficherNote();
                actualiserMenu();

                return;

            end

        end

    end

% ============================================================
% CLIC TOUCHE NOIRE DU CLAVIER
% ============================================================

    function clicToucheNoire(~,~,indice)

        nom = nomsNoires{indice};

        note = strrep(nom,'5','');
        note = strrep(note,'6','');

        tableau = {'C#','D#','F#','G#','A#'};

        for i = 1:5

            if strcmp(tableau{i},note)

                noteSelectionnee = i;
                typeNoteSelectionne = 2;

                afficherNote();
                actualiserMenu();

                return;

            end

        end

    end

% ============================================================
% OUVRIR GAMMES
% ============================================================

    function ouvrirGammes(~,~)

        try

            set(f,'Visible','off');

            gammes(f,codeLangue);

        catch erreur

            set(f,'Visible','on');

            errordlg( ...
                erreur.message, ...
                'EDU-PIANO & IT');

        end

    end

% ============================================================
% RETOUR AU PIANO
% ============================================================

    function retourPiano(~,~)

        try
            delete(f);
        catch
        end

        if ~isempty(parentFigure) && ...
                ishandle(parentFigure)

            set( ...
                parentFigure, ...
                'Visible','on');

            figure(parentFigure);

        else

            try
                piano([],codeLangue);
            catch
                piano();
            end

        end

    end

% ============================================================
% PLEIN ECRAN
% ============================================================

    function basculerPleinEcran(~,~)

        if ~pleinEcran

            positionNormale = ...
                get(f,'Position');

            try

                set(f,'WindowState','maximized');

            catch

                set( ...
                    f, ...
                    'Position',[ ...
                    ecran(1) ...
                    ecran(2) ...
                    ecran(3) ...
                    ecran(4)]);

            end

            pleinEcran = true;

            set( ...
                boutonPleinEcran, ...
                'String',langue('taille_normale',codeLangue));

        else

            try

                set(f,'WindowState','normal');

            catch
            end

            set( ...
                f, ...
                'Position',positionNormale);

            pleinEcran = false;

            set( ...
                boutonPleinEcran, ...
                'String',langue('plein_ecran',codeLangue));

        end

    end

% ============================================================
% TOUCHE ECHAP
% ============================================================

    function toucheClavier(~,event)

        if strcmp(event.Key,'escape')

            if pleinEcran

                try
                    set(f,'WindowState','normal');
                catch
                end

                set( ...
                    f, ...
                    'Position',positionNormale);

                pleinEcran = false;

                set( ...
                    boutonPleinEcran, ...
                    'String',langue('plein_ecran',codeLangue));

            end

        end

    end

