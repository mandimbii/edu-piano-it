% 24. FERMETURE
% ============================================================

function fermerFenetre(~,~)

    parentExiste = false;

    if ~isempty(parentFigure)

        try
            parentExiste = ishandle(parentFigure);
        catch
            parentExiste = false;
        end

    end

    try
        delete(f);
    catch
    end

    if parentExiste

        try
            set(parentFigure,'Visible','on');
            figure(parentFigure);
        catch
        end

    end

end


