function selectionPartie(~,~,indice)

    chapitreActuel = indice;

    actualiserCours();

end


% ============================================================
% 18. ACTUALISER LE COURS
% ============================================================

function actualiserCours()

    nombre = length(parties);

    if chapitreActuel < 1
        chapitreActuel = 1;
    end

    if chapitreActuel > nombre
        chapitreActuel = nombre;
    end

    set(texteChapitre, ...
        'String',parties{chapitreActuel});

    set(texteCours, ...
        'String',cours{chapitreActuel}, ...
        'Value',1);

    set(texteIndicateur, ...
        'String',sprintf('%d / %d', ...
        chapitreActuel,nombre));

    % --------------------------------------------------------
    % Boutons des parties
    % --------------------------------------------------------

    for k = 1:nombre

        if k == chapitreActuel

            set(boutonsChapitres{k}, ...
                'BackgroundColor',vert, ...
                'ForegroundColor',blanc);

        else

            set(boutonsChapitres{k}, ...
                'BackgroundColor',blanc, ...
                'ForegroundColor',bleuFonce);

        end

    end

    % --------------------------------------------------------
    % Etat des boutons navigation
    % --------------------------------------------------------

    if chapitreActuel == 1

        set(boutonPrecedent, 'Enable','off');

    else

        set(boutonPrecedent, 'Enable','on');

    end

    if chapitreActuel == nombre

        set(boutonSuivant, 'Enable','off');

    else

        set(boutonSuivant, 'Enable','on');

    end

end


% ============================================================
% 19. PRECEDENT
% ============================================================

function precedent(~,~)

    if chapitreActuel > 1

        chapitreActuel = chapitreActuel - 1;

        actualiserCours();

    end

end


% ============================================================
% 20. SUIVANT
% ============================================================

function suivant(~,~)

    if chapitreActuel < length(parties)

        chapitreActuel = chapitreActuel + 1;

        actualiserCours();

    end

end


% ============================================================
% 21. RETOUR
% ============================================================

function retourAccueil(~,~)

    parentExiste = false;

    if ~isempty(parentFigure)

        try
            parentExiste = ishandle(parentFigure);
        catch
            parentExiste = false;
        end

    end

    if parentExiste

        set(f,'Visible','off');
        set(parentFigure,'Visible','on');

        try
            figure(parentFigure);
        catch
        end

    else

        set(f,'Visible','off');

        try
            main();
        catch
        end

    end

end


% ============================================================
% 22. PLEIN ECRAN
% ============================================================

function pleinEcran(~,~)

    if ~ishandle(f)
        return;
    end

    try

        etat = get(f,'WindowState');

        if strcmp(etat,'maximized')

            set(f,'WindowState','normal');

            estPleinEcran = false;

            set(btnPleinEcran, ...
                'String',langue('plein_ecran',codeLangue));

        else

            set(f,'WindowState','maximized');

            estPleinEcran = true;

            set(btnPleinEcran, ...
                'String',langue('taille_normale',codeLangue));

        end

    catch

        try

            positionActuelle = get(f,'Position');

            if estPleinEcran

                set(f,'Position',positionNormale);

                estPleinEcran = false;

                set(btnPleinEcran, ...
                    'String',langue('plein_ecran',codeLangue));

            else

                set(f,'Position',ecran);

                estPleinEcran = true;

                set(btnPleinEcran, ...
                    'String',langue('taille_normale',codeLangue));

            end

        catch

        end

    end

end


% ============================================================
% 23. CLAVIER
% ============================================================

function toucheClavier(~,event)

    if ~isfield(event,'Key')
        return;
    end

    touche = lower(event.Key);

    switch touche

        case 'escape'

            try
                set(f,'WindowState','normal');
            catch
            end

            try
                set(f,'Position',positionNormale);
            catch
            end

            estPleinEcran = false;

            try

                set(btnPleinEcran, ...
                    'String',langue('plein_ecran',codeLangue));

            catch

            end

        case 'rightarrow'

            suivant();

        case 'leftarrow'

            precedent();

    end

end


