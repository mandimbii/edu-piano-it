            'EDU-PIANO & IT');

    end

end


% ============================================================
% 29. RETOUR ACCUEIL
% ============================================================

function retourAccueil(~,~)

    parentExiste = false;


    if ~isempty(parentFigure)

        try

            parentExiste = ishandle(parentFigure);

        catch

            parentExiste = false;

        end

    end


    if parentExiste

        % ----------------------------------------------------
        % Fermer Informatique
        % ----------------------------------------------------

        try

            if ishandle(f)
                delete(f);
            end

        catch

        end


        % ----------------------------------------------------
        % Afficher le MEME main.m
        % ----------------------------------------------------

        try

            set(parentFigure,'Visible','on');

            figure(parentFigure);

        catch

        end

    else

        % ----------------------------------------------------
        % Aucun parent disponible
        % ----------------------------------------------------

        try

            if ishandle(f)
                delete(f);
            end

        catch

        end

    end

end


% ============================================================
% 30. PLEIN ECRAN
% ============================================================

function pleinEcran(~,~)

    if ~ishandle(f)
        return;
    end

    try

        etat = get(f,'WindowState');

        if strcmp(etat,'maximized')

            set(f,'WindowState','normal');

            estPleinEcran = false;

            set(btnPleinEcran, ...
                'String',langue('plein_ecran',codeLangue));

        else

            set(f,'WindowState','maximized');

            estPleinEcran = true;

            set(btnPleinEcran, ...
                'String',langue('taille_normale',codeLangue));

        end

    catch

        % Compatibilite GNU Octave

        try

            positionActuelle = get(f,'Position');

            if estPleinEcran

                set(f,'Position',positionNormale);

                estPleinEcran = false;

                set(btnPleinEcran, ...
                    'String',langue('plein_ecran',codeLangue));

            else

                set(f,'Position',ecran);

                estPleinEcran = true;

                set(btnPleinEcran, ...
                    'String',langue('taille_normale',codeLangue));

            end

        catch

        end

    end

end


% ============================================================
% 31. TOUCHE ECHAP / FLECHES
% ============================================================

function toucheClavier(~,event)

    if ~isfield(event,'Key')
        return;
    end

    touche = lower(event.Key);

    switch touche

        case 'escape'

            try
                set(f,'WindowState','normal');
            catch
            end

            try
                set(f,'Position',positionNormale);
            catch
            end

            estPleinEcran = false;

            try

                set(btnPleinEcran, ...
                    'String',langue('plein_ecran',codeLangue));

            catch

            end

        case 'rightarrow'

            suivant();

        case 'leftarrow'

            precedent();

    end

end


