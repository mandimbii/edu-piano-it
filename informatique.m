function selectionMatiere(~,~,indice)

    matiereActuelle = indice;
    chapitreActuel = 1;

    actualiserMatiere();

end


% ============================================================
% 23. ACTUALISER MATIERE
% ============================================================

function actualiserMatiere()

    set(texteMatiere, ...
        'String',nomsMatieres{matiereActuelle});

    set(texteDescription, ...
        'String',descriptionsMatieres{matiereActuelle}, ...
        'Value',1);


    for i = 1:7

        if i == matiereActuelle

            set(boutonsMatieres{i}, ...
                'BackgroundColor',vert, ...
                'ForegroundColor',blanc);

        else

            set(boutonsMatieres{i}, ...
                'BackgroundColor',bleuClair, ...
                'ForegroundColor',bleuFonce);

        end

    end


    % --------------------------------------------------------
    % Supprimer anciens boutons chapitres
    % --------------------------------------------------------

    for i = 1:length(boutonsChapitres)

        if ~isempty(boutonsChapitres{i})

            try

                if ishandle(boutonsChapitres{i})
                    delete(boutonsChapitres{i});
                end

            catch

            end

            boutonsChapitres{i} = [];

        end

    end


    % --------------------------------------------------------
    % Creer nouveaux boutons
    % --------------------------------------------------------

    liste = chapitres{matiereActuelle};

    nombreChapitres = length(liste);

    zoneHaut = 0.745;
    zoneBas = 0.17;

    hauteurZone = zoneHaut - zoneBas;

    espacement = hauteurZone / nombreChapitres;

    hauteurBouton = min(0.06,espacement*0.72);


    for j = 1:nombreChapitres

        yBouton = ...
            zoneHaut - j*espacement + ...
            (espacement-hauteurBouton)/2;


        boutonsChapitres{j} = uicontrol( ...
            'Parent',f, ...
            'Style','pushbutton', ...
            'Units','normalized', ...
            'Position',[0.205 yBouton 0.21 hauteurBouton], ...
            'String',liste{j}, ...
            'FontSize',8, ...
            'FontWeight','bold', ...
            'ForegroundColor',bleuFonce, ...
            'BackgroundColor',blanc, ...
            'HorizontalAlignment','left', ...
            'Callback',{@selectionChapitre,j});

    end


    actualiserCours();

end


% ============================================================
% 24. SELECTION CHAPITRE
% ============================================================

function selectionChapitre(~,~,indice)

    chapitreActuel = indice;

    actualiserCours();

end


% ============================================================
% 25. ACTUALISER COURS
% ============================================================

function actualiserCours()

    liste = chapitres{matiereActuelle};

    nombreChapitres = length(liste);


    if chapitreActuel < 1
        chapitreActuel = 1;
    end


    if chapitreActuel > nombreChapitres
        chapitreActuel = nombreChapitres;
    end


    set(texteChapitre, ...
        'String',liste{chapitreActuel});


    set(texteCours, ...
        'String',cours{matiereActuelle}{chapitreActuel}, ...
        'Value',1);


    set(texteIndicateur, ...
        'String',sprintf('%d / %d', ...
        chapitreActuel,nombreChapitres));


    for i = 1:nombreChapitres

        if ~isempty(boutonsChapitres{i})

            if i == chapitreActuel

                set(boutonsChapitres{i}, ...
                    'BackgroundColor',vert, ...
                    'ForegroundColor',blanc);

            else

                set(boutonsChapitres{i}, ...
                    'BackgroundColor',blanc, ...
                    'ForegroundColor',bleuFonce);

            end

        end

    end

    % --------------------------------------------------------
    % Etat des boutons navigation
    % --------------------------------------------------------

    if chapitreActuel == 1 && matiereActuelle == 1

        set(boutonPrecedent, 'Enable','off');

    else

        set(boutonPrecedent, 'Enable','on');

    end

    if chapitreActuel == nombreChapitres && ...
       matiereActuelle == length(nomsMatieres)

        set(boutonSuivant, 'Enable','off');

    else

        set(boutonSuivant, 'Enable','on');

    end

end


% ============================================================
% 26. PRECEDENT
% ============================================================

function precedent(~,~)

    if chapitreActuel > 1

        chapitreActuel = chapitreActuel - 1;

        actualiserCours();

        return;

    end


    if matiereActuelle > 1

        matiereActuelle = matiereActuelle - 1;

        chapitreActuel = length(chapitres{matiereActuelle});

        actualiserMatiere();

    end

end


% ============================================================
% 27. SUIVANT
% ============================================================

function suivant(~,~)

    nombreChapitres = ...
        length(chapitres{matiereActuelle});


    if chapitreActuel < nombreChapitres

        chapitreActuel = chapitreActuel + 1;

        actualiserCours();

        return;

    end


    if matiereActuelle < length(nomsMatieres)

        matiereActuelle = matiereActuelle + 1;

        chapitreActuel = 1;

        actualiserMatiere();

    end

end


