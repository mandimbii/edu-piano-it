% ============================================================
% 21. FONCTION DE MISE A JOUR DE LA LANGUE (A CHAUD)
% ============================================================

function miseAJourLangue(nouvelleLangue)

    % Mettre a jour la variable locale
    if nargin >= 1 && ~isempty(nouvelleLangue)
        codeLangue = upper(nouvelleLangue);
    end

    % Verifier que la figure existe toujours
    if ~ishandle(f)
        return;
    end

    % --------------------------------------------------------
    % Mise a jour de tous les textes
    % --------------------------------------------------------

    try

        % Titre gauche
        if ishandle(handlesLangue.txtTitreGauche)
            set(handlesLangue.txtTitreGauche, ...
                'String',langue('informatique',codeLangue));
        end

        % "MATIERES"
        if ishandle(handlesLangue.txtMatieres)
            set(handlesLangue.txtMatieres, ...
                'String',langue('matieres',codeLangue));
        end

        % "THEORIE GENERALE"
        if ishandle(handlesLangue.btnTheorieGen)
            set(handlesLangue.btnTheorieGen, ...
                'String',langue('theorie_generale',codeLangue));
        end

        % "RETOUR"
        if ishandle(handlesLangue.btnRetour)
            set(handlesLangue.btnRetour, ...
                'String',langue('retour',codeLangue));
        end

        % "CHAPITRES"
        if ishandle(handlesLangue.txtChapitres)
            set(handlesLangue.txtChapitres, ...
                'String',langue('chapitres_titre',codeLangue));
        end

        % "COURS D'INFORMATIQUE"
        if ishandle(handlesLangue.txtCoursTitre)
            set(handlesLangue.txtCoursTitre, ...
                'String',langue('cours_informatique',codeLangue));
        end

        % "PRECEDENT"
        if ishandle(boutonPrecedent)
            set(boutonPrecedent, ...
                'String',langue('precedent',codeLangue));
        end

        % "SUIVANT"
        if ishandle(boutonSuivant)
            set(boutonSuivant, ...
                'String',langue('suivant',codeLangue));
        end

        % "PLEIN ECRAN"
        if ishandle(btnPleinEcran)
            set(btnPleinEcran, ...
                'String',langue('plein_ecran',codeLangue));
        end

    catch

        % En cas d'erreur, on ignore silencieusement

    end

end


% ============================================================
% 22. SELECTION MATIERE
