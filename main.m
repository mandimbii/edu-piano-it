% ============================================================
% 26. CHANGEMENT DE LANGUE
% ============================================================

function changerLangue(src,~)

    valeur = get(src,'Value');

    switch valeur

        case 1
            codeLangue = 'FR';

        case 2
            codeLangue = 'MG';

        case 3
            codeLangue = 'EN';

        otherwise
            codeLangue = 'FR';

    end

    try
        save(fichierPreferences,'codeLangue');
    catch
    end

    actualiserLangue();

    notifierChangementLangue(codeLangue);

end


% ============================================================
% 27. NOTIFIER LES MODULES OUVERTS
% ============================================================

function notifierChangementLangue(nouvelleLangue)

    try
        toutesFigures = findall(0,'Type','figure');
    catch
        toutesFigures = [];
    end

    if isempty(toutesFigures)
        return;
    end

    for k = 1:length(toutesFigures)

        fig = toutesFigures(k);

        try

            cb = getappdata(fig,'callbackLangue');

            if ~isempty(cb) && isa(cb,'function_handle')

                try
                    cb(nouvelleLangue);
                catch
                end

            end

        catch

        end

    end

end


