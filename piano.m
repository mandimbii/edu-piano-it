% ============================================================
% 30. RETOUR ACCUEIL
% ============================================================

function retourAccueil(~,~)

    parentExiste = false;

    if ~isempty(parentFigure)

        try

            if ishandle(parentFigure)
                parentExiste = true;
            end

        catch

            parentExiste = false;

        end

    end


    % Fermer le module PIANO
    try

        if ishandle(f)
            delete(f);
        end

    catch

        try
            close(f);
        catch
        end

    end


    % Retour vers le meme MAIN
    if parentExiste

        try

            set(parentFigure,'Visible','on');
            figure(parentFigure);

        catch

            try
                set(parentFigure,'Visible','on');
            catch
            end

        end

    end

end


% ============================================================
% 31. PLEIN ECRAN
% ============================================================

function pleinEcran(~,~)

    if ~ishandle(f)
        return;
    end

    try

        etat = get(f,'WindowState');

        if strcmp(etat,'maximized')

            set(f,'WindowState','normal');

            estPleinEcran = false;

            set(btnPleinEcran, ...
                'String',langue('plein_ecran',codeLangue));

        else

            set(f,'WindowState','maximized');

            estPleinEcran = true;

            set(btnPleinEcran, ...
                'String',langue('taille_normale',codeLangue));

        end

    catch

        % Compatibilite GNU Octave

        try

            positionActuelle = get(f,'Position');

            if estPleinEcran

                set(f,'Position',positionNormale);

                estPleinEcran = false;

                set(btnPleinEcran, ...
                    'String',langue('plein_ecran',codeLangue));

            else

                set(f,'Position',ecran);

                estPleinEcran = true;

                set(btnPleinEcran, ...
                    'String',langue('taille_normale',codeLangue));

            end

        catch

        end

    end

end


% ============================================================
% 32. TOUCHE ECHAP
% ============================================================

function toucheClavier(~,event)

    if ~isfield(event,'Key')
        return;
    end

    if strcmpi(event.Key,'escape')

        try
            set(f,'WindowState','normal');
        catch
        end

        try
            set(f,'Position',positionNormale);
        catch
        end

        estPleinEcran = false;

        try

            set(btnPleinEcran, ...
                'String',langue('plein_ecran',codeLangue));

        catch

        end

    end

end


% ============================================================
% 33. QUITTER LE MODULE
% ============================================================

function quitterPiano(~,~)

    choix = questdlg( ...
        'Voulez-vous quitter EDU-PIANO & IT ?', ...
        'Quitter', ...
        'Oui', ...
        'Non', ...
        'Non');

    if strcmp(choix,'Oui')

        % Fermer Piano
        try
            delete(f);
        catch
        end

        % Fermer egalement le parent = quitter completement
        try

            if ~isempty(parentFigure) && ishandle(parentFigure)
                delete(parentFigure);
            end

        catch

        end

    end

end


% ============================================================
