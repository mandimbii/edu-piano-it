            delete(f);
        end

    catch

    end


    % Montrer le meme main.m
    if parentExiste

        try

            set(parentFigure,'Visible','on');
            figure(parentFigure);

        catch

            try
                set(parentFigure,'Visible','on');
            catch
            end

        end

    end

end


