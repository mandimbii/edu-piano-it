% ============================================================
% 18. SELECTION CHAPITRE
% ============================================================

function selectionChapitre(~,~,indice)

    if indice >= 1 && indice <= nombreChapitres

        chapitreActuel = indice;

        afficherChapitre();

    end

end


% ============================================================
% 19. PRECEDENT
% ============================================================

function chapitrePrecedent(~,~)

    if chapitreActuel > 1

        chapitreActuel = chapitreActuel - 1;

        afficherChapitre();

    end

end


% ============================================================
% 20. SUIVANT
% ============================================================

function chapitreSuivant(~,~)

    if chapitreActuel < nombreChapitres

        chapitreActuel = chapitreActuel + 1;

        afficherChapitre();

    end

end


% ============================================================
% 21. AFFICHAGE CHAPITRE
% ============================================================

function afficherChapitre()

    % --------------------------------------------------------
    % Numero
    % --------------------------------------------------------

    set(texteNumero, ...
        'String',sprintf('CHAPITRE %d',chapitreActuel));

    % --------------------------------------------------------
    % Titre sans numero
    % --------------------------------------------------------

    titre = titresChapitres{chapitreActuel};

    positionPoint = find(titre == '.',1);

    if ~isempty(positionPoint)

        titreSimple = strtrim( ...
            titre(positionPoint+1:end));

    else

        titreSimple = titre;

    end

    set(texteTitre, ...
        'String',titreSimple);

    % --------------------------------------------------------
    % Contenu
    % --------------------------------------------------------

    set(texteCours, ...
        'String',cours{chapitreActuel}, ...
        'Value',1);

    % --------------------------------------------------------
    % Bouton actif
    % --------------------------------------------------------

    for i = 1:nombreChapitres

        if i == chapitreActuel

            set(boutonsChapitres{i}, ...
                'BackgroundColor',vert, ...
                'ForegroundColor',blanc);

        else

            set(boutonsChapitres{i}, ...
                'BackgroundColor',bleuClair, ...
                'ForegroundColor',bleuFonce);

        end

    end

    % --------------------------------------------------------
    % Indicateur
    % --------------------------------------------------------

    if ~isempty(texteIndicateur) && ishandle(texteIndicateur)

        set(texteIndicateur, ...
            'String',sprintf('%d / %d', ...
            chapitreActuel,nombreChapitres));

    end

end


% ============================================================
% 22. RETOUR AU PIANO (ou MAIN)
% ============================================================

function retourPiano(~,~)

    parentExiste = false;

    if ~isempty(parentFigure)

        try
            parentExiste = ishandle(parentFigure);
        catch
            parentExiste = false;
        end

    end

    % --------------------------------------------------------
    % Cacher cette fenetre
    % --------------------------------------------------------

    if parentExiste

        set(f,'Visible','off');

        try

            set(parentFigure,'Visible','on');
            figure(parentFigure);

        catch

            try
                set(parentFigure,'Visible','on');
            catch
            end

        end

    else

        % ----------------------------------------------------
        % Aucun parent : fermer et relancer piano.m
        % ----------------------------------------------------

        try

            if ishandle(f)
                delete(f);
            end

        catch

        end

        try
            piano([],codeLangue);
        catch
            try
                piano();
            catch
            end
        end

    end

end


% ============================================================
% 23. PLEIN ECRAN
% ============================================================

function pleinEcran(~,~)

    if ~ishandle(f)
        return;
    end

    try

        etat = get(f,'WindowState');

        if strcmp(etat,'maximized')

            set(f,'WindowState','normal');

            estPleinEcran = false;

            set(btnPleinEcran, ...
                'String',langue('plein_ecran',codeLangue));

        else

            set(f,'WindowState','maximized');

            estPleinEcran = true;

            set(btnPleinEcran, ...
                'String',langue('taille_normale',codeLangue));

        end

    catch

        % Compatibilite GNU Octave

        try

            positionActuelle = get(f,'Position');

            if estPleinEcran

                set(f,'Position',positionNormale);

                estPleinEcran = false;

                set(btnPleinEcran, ...
                    'String',langue('plein_ecran',codeLangue));

            else

                set(f,'Position',ecran);

                estPleinEcran = true;

                set(btnPleinEcran, ...
                    'String',langue('taille_normale',codeLangue));

            end

        catch

        end

    end

end


% ============================================================
% 24. TOUCHE ECHAP
% ============================================================

function toucheClavier(~,event)

    if ~isfield(event,'Key')
        return;
    end

    touche = lower(event.Key);

    switch touche

        case 'escape'

            try
                set(f,'WindowState','normal');
            catch
            end

            try
                set(f,'Position',positionNormale);
            catch
            end

            estPleinEcran = false;

            try

                set(btnPleinEcran, ...
                    'String',langue('plein_ecran',codeLangue));

            catch

            end

        case 'leftarrow'

            chapitrePrecedent();

        case 'rightarrow'

            chapitreSuivant();

    end

end


% ============================================================
% 25. FERMETURE
% ============================================================

function fermerFenetre(~,~)

    parentExiste = false;

    try

        if ~isempty(parentFigure) && ishandle(parentFigure)
            parentExiste = true;
        end

    catch

        parentExiste = false;

    end

    try

        if ishandle(f)
            delete(f);
        end

    catch

    end

    if parentExiste

        try

            set(parentFigure,'Visible','on');
            figure(parentFigure);

        catch

            try
                set(parentFigure,'Visible','on');
            catch
            end

        end

    end

end


